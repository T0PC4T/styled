import 'package:flutter/widgets.dart';

import '../theme/styled_theme.dart';

/// A themeable value in a style, resolved against the active [StyledTheme]
/// when a widget builds.
///
/// Every design value in a style (colours, sizes, spacing, radii, font sizes,
/// durations) is a [StyleValue], never a raw value. The family is sealed, so
/// the only ways to provide one are:
///
/// | Kind | Example | Meaning |
/// |---|---|---|
/// | [ThemeToken] | `AppTokens.primary` | A design token, looked up in the theme |
/// | [AlphaOf] | `AlphaOf(AppTokens.primary, AppTokens.opacitySubtle)` | A colour at an opacity from the scale |
/// | [DataValue] | `DataValue(tag.color)` | Runtime data, such as a user-chosen colour |
/// | [StyleValue.zero], [StyleValue.infinity] | `width: StyleValue.infinity` | Layout constants |
///
/// There is no arithmetic: a value either comes from the theme's scale, from
/// data, or is a layout constant. That keeps every component on the same
/// scale, and makes every design value change with the theme.
@immutable
sealed class StyleValue<T> {
  const StyleValue();

  /// The concrete value in [theme].
  T resolve(StyledTheme theme);

  /// Zero, as a layout constant.
  static const StyleValue<double> zero = _LayoutValue(0.0, 'zero');

  /// Infinity, as a layout constant: fill the available space.
  static const StyleValue<double> infinity = _LayoutValue(double.infinity, 'infinity');
}

/// A typed design token: a key into [StyledTheme] plus the value used when
/// the theme does not set it.
///
/// Generated by `@StyledTokens`, or declared by hand:
///
/// ```dart
/// const primary = ThemeToken<Color>('primary', Color(0xFF2563EB));
/// ```
final class ThemeToken<T> extends StyleValue<T> {
  final String key;
  final T defaultValue;

  const ThemeToken(this.key, this.defaultValue);

  @override
  T resolve(StyledTheme theme) => theme.get(this);

  @override
  bool operator ==(Object other) =>
      identical(this, other) ||
      (other is ThemeToken<dynamic> && runtimeType == other.runtimeType && key == other.key);

  @override
  int get hashCode => key.hashCode;

  @override
  String toString() => 'ThemeToken<$T>($key, default: $defaultValue)';
}

/// A runtime data value, such as a user-chosen tag colour or a requested
/// width. It is the same in every theme.
///
/// Use it only for values that come from data, never for design decisions:
/// those belong in tokens. Searching for `DataValue(` finds every place a
/// style takes a value from outside the theme.
final class DataValue<T> extends StyleValue<T> {
  final T value;

  const DataValue(this.value);

  /// A [DataValue] for [value], or null when [value] is null.
  static DataValue<T>? of<T extends Object>(T? value) => value == null ? null : DataValue<T>(value);

  @override
  T resolve(StyledTheme theme) => value;

  @override
  bool operator ==(Object other) => identical(this, other) || other is DataValue<T> && value == other.value;

  @override
  int get hashCode => value.hashCode;

  @override
  String toString() => 'DataValue($value)';
}

/// A colour at an opacity taken from the theme's opacity scale.
///
/// The opacity must be a token, so components cannot drift onto one-off
/// levels: `AlphaOf(AppTokens.primary, AppTokens.opacitySubtle)`.
final class AlphaOf extends StyleValue<Color> {
  final StyleValue<Color> color;
  final ThemeToken<double> opacity;

  const AlphaOf(this.color, this.opacity);

  @override
  Color resolve(StyledTheme theme) => color.resolve(theme).withValues(alpha: theme.get(opacity));

  @override
  bool operator ==(Object other) =>
      identical(this, other) || other is AlphaOf && color == other.color && opacity == other.opacity;

  @override
  int get hashCode => Object.hash(color, opacity);

  @override
  String toString() => 'AlphaOf($color, $opacity)';
}

final class _LayoutValue<T> extends StyleValue<T> {
  final T value;
  final String name;

  const _LayoutValue(this.value, this.name);

  @override
  T resolve(StyledTheme theme) => value;

  @override
  bool operator ==(Object other) => identical(this, other) || other is _LayoutValue<T> && value == other.value;

  @override
  int get hashCode => value.hashCode;

  @override
  String toString() => 'StyleValue.$name';
}

/// One step of a shadow scale: opacity, blur, spread and offset. Used as the
/// value of a shadow token, and applied to a colour by
/// `StyledBoxShadow.level`.
@immutable
class ShadowLevel {
  final double opacity;
  final double blurRadius;
  final double spreadRadius;
  final double dx;
  final double dy;

  const ShadowLevel({required this.opacity, required this.blurRadius, this.spreadRadius = 0, this.dx = 0, this.dy = 0});

  @override
  bool operator ==(Object other) =>
      identical(this, other) ||
      other is ShadowLevel &&
          opacity == other.opacity &&
          blurRadius == other.blurRadius &&
          spreadRadius == other.spreadRadius &&
          dx == other.dx &&
          dy == other.dy;

  @override
  int get hashCode => Object.hash(opacity, blurRadius, spreadRadius, dx, dy);

  @override
  String toString() => 'ShadowLevel(opacity: $opacity, blur: $blurRadius, offset: ($dx, $dy))';
}
